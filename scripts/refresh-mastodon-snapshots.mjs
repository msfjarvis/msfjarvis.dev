#!/usr/bin/env node
/**
 * Snapshots every MastodonPost referenced by site MDX.
 *
 * This is intentionally networked and must be run after adding or changing an
 * embed. Site builds consume only the generated source file.
 */
import {
  fetchMastodonStatus,
  getMastodonSnapshotKey,
} from "../src/lib/mastodon.ts";
import { mkdir, readFile, readdir, rename, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
export const PROJECT_ROOT = resolve(SCRIPT_DIR, "..");
export const SNAPSHOT_MODULE = join(
  PROJECT_ROOT,
  "src/data/mastodon-snapshots.ts",
);

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries
      .sort((a, b) => a.name.localeCompare(b.name))
      .map(async (entry) => {
        const path = join(directory, entry.name);
        if (entry.isDirectory()) return sourceFiles(path);
        return entry.isFile() && /\.(astro|mdx)$/.test(entry.name)
          ? [path]
          : [];
      }),
  );
  return nested.flat();
}

function activeComponentSource(source) {
  return source
    .replace(/```[\s\S]*?```/g, "")
    .replace(/~~~[\s\S]*?~~~/g, "")
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/(`+)([\s\S]*?)\1/g, "");
}

export function extractMastodonUrls(source, file = "source") {
  const urls = [];
  const tags = activeComponentSource(source).matchAll(
    /<MastodonPost\b([\s\S]*?)\/>/g,
  );
  for (const tag of tags) {
    const attributes = tag[1];
    const url = attributes.match(
      /\burl\s*=\s*(?:"([^"]+)"|'([^']+)'|\{\s*"([^"]+)"\s*\}|\{\s*'([^']+)'\s*\})/,
    );
    const literalUrl = url?.slice(1).find(Boolean);
    if (!literalUrl) {
      throw new Error(
        `MastodonPost in ${file} must provide url as a string literal.`,
      );
    }
    urls.push(literalUrl);
  }
  return urls;
}

export async function collectMastodonUrls(sourceDirectory) {
  const files = await sourceFiles(sourceDirectory);
  const urls = await Promise.all(
    files.map(async (file) =>
      extractMastodonUrls(await readFile(file, "utf8"), file),
    ),
  );
  return [...new Set(urls.flat().map(getMastodonSnapshotKey))].sort();
}

export function snapshotModuleSource(snapshots) {
  return `// Generated by scripts/refresh-mastodon-snapshots.mjs — do not edit by hand.\n// Regenerate with: pnpm mastodon:refresh\nimport type { MastodonStatus } from "../lib/mastodon.ts";\n\nexport const mastodonSnapshots = ${JSON.stringify(snapshots, null, 2)} satisfies Record<string, MastodonStatus>;\n`;
}

export async function writeSnapshotModule(
  snapshots,
  outputPath = SNAPSHOT_MODULE,
) {
  await mkdir(dirname(outputPath), { recursive: true });
  const temporaryPath = `${outputPath}.tmp`;
  await writeFile(temporaryPath, snapshotModuleSource(snapshots), "utf8");
  await rename(temporaryPath, outputPath);
}

export async function refreshMastodonSnapshots({
  sourceDirectory = join(PROJECT_ROOT, "src"),
  outputPath = SNAPSHOT_MODULE,
  fetchImpl,
} = {}) {
  const urls = await collectMastodonUrls(sourceDirectory);
  const statuses = await Promise.all(
    urls.map((url) => fetchMastodonStatus({ url, fetchImpl })),
  );
  const snapshots = Object.fromEntries(
    statuses
      .map((status) => [status.canonicalUrl, status])
      .sort(([left], [right]) => left.localeCompare(right)),
  );
  await writeSnapshotModule(snapshots, outputPath);
  return urls.length;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  refreshMastodonSnapshots()
    .then((count) =>
      console.log(
        `✓ refreshed ${count} Mastodon snapshot${count === 1 ? "" : "s"}`,
      ),
    )
    .catch((error) => {
      console.error(error);
      process.exitCode = 1;
    });
}
